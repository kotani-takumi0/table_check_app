// 画面の版（v2.3.3）でも package.json の版（2.3.3）でも引ける
export function releaseNoteOf(version: string): ReleaseNote | undefined {
  const bare = version.replace(/^v/, '');
  return RELEASE_NOTES.find(note => note.version === bare);
}

// 新しい版になったあと、その版のお知らせを1回だけ出す。見た版はこの端末に覚える（端末ごと）
export const SEEN_RELEASE_KEY = 'minopal:seenRelease';
// seen：この端末で最後に見た（閉じた）版。まだ無ければ null（この機能が入る前から使っている端末も、最初の1回は出す）
export function shouldAnnounce(seen: string | null, current: string): boolean {
  const note = releaseNoteOf(current);
  return note !== undefined && seen !== note.version;
}

// 「2026-10-07」→「2026年10月7日」
export function releaseDateLabel(date: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date);
  return match ? `${match[1]}年${Number(match[2])}月${Number(match[3])}日` : date;
}
